CREATE FUNCTION search_cases(
    p_start_date date DEFAULT NULL,
    p_end_date date DEFAULT NULL,
    p_city character varying DEFAULT NULL,
    p_status character varying DEFAULT NULL
)
RETURNS TABLE(
    case_id integer,
    case_number character varying,
    matter_title character varying,
    cause_date date,
    case_status character varying,
    location text,
    lead_counsel text
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT
        lc.case_id,
        lc.case_number,
        lc.matter_title,
        lc.date_cause,
        lc.status,
        concat(loc.landmark, ', ', pa.city),
        (SELECT concat(lw.fname, ' ', lw.lname)
         FROM case_lawyer cl
         JOIN lawyer lw ON cl.lawyer_id = lw.lawyer_id
         WHERE cl.case_id = lc.case_id AND cl.role = 'Lead Counsel' AND cl.end_date IS NULL
         LIMIT 1)
    FROM legal_case lc
    LEFT JOIN location loc ON lc.location_id = loc.location_id
    LEFT JOIN pincode_area pa ON loc.pincode = pa.pincode
    WHERE (p_start_date IS NULL OR lc.date_cause >= p_start_date)
      AND (p_end_date IS NULL OR lc.date_cause <= p_end_date)
      AND (p_city IS NULL OR pa.city ILIKE '%' || p_city || '%')
      AND (p_status IS NULL OR lc.status = p_status)
    ORDER BY lc.date_cause DESC;
END;
$$;

CREATE FUNCTION log_case_status_change() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.status IS DISTINCT FROM NEW.status THEN
        INSERT INTO case_status_audit (case_id, old_status, new_status)
        VALUES (NEW.case_id, OLD.status, NEW.status);
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION advance_case_on_evidence() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE legal_case
    SET status = 'Hearing'
    WHERE case_id = NEW.case_id
      AND status = 'Filed';
    RETURN NEW;
END;
$$;
COMMENT ON FUNCTION advance_case_on_evidence IS 'Filing the first evidence item moves a Filed matter to Hearing.';

CREATE FUNCTION mark_repeat_opposing_party() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF (SELECT count(*) FROM case_opposing_party WHERE party_id = NEW.party_id) > 1 THEN
        UPDATE opposing_party
        SET repeat_party = true
        WHERE party_id = NEW.party_id;
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION validate_legal_case_dates() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.date_filed < NEW.date_cause THEN
        RAISE EXCEPTION 'Filing date (%) cannot be before the cause of action (%)', NEW.date_filed, NEW.date_cause;
    END IF;
    IF NEW.date_cause > CURRENT_DATE THEN
        RAISE EXCEPTION 'Cause of action (%) cannot be in the future', NEW.date_cause;
    END IF;
    IF NEW.date_filed > CURRENT_DATE THEN
        RAISE EXCEPTION 'Filing date (%) cannot be in the future', NEW.date_filed;
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION validate_evidence_date() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_cause date;
BEGIN
    SELECT date_cause INTO v_cause FROM legal_case WHERE case_id = NEW.case_id;
    IF v_cause IS NOT NULL AND NEW.filed_date < v_cause THEN
        RAISE EXCEPTION 'Evidence date (%) cannot be before the cause of action (%)', NEW.filed_date, v_cause;
    END IF;
    IF NEW.filed_date > CURRENT_DATE THEN
        RAISE EXCEPTION 'Evidence date (%) cannot be in the future', NEW.filed_date;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER case_status_audit
    AFTER UPDATE ON legal_case
    FOR EACH ROW EXECUTE FUNCTION log_case_status_change();

