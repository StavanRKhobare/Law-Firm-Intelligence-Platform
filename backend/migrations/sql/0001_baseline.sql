CREATE TABLE practice_group (
    group_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name character varying(100) NOT NULL,
    description text,
    email character varying(100) UNIQUE,
    contactno character varying(15)
);
COMMENT ON TABLE practice_group IS 'Teams inside the one firm. The firm itself is the database boundary.';

CREATE TABLE pincode_area (
    pincode character varying(10) PRIMARY KEY,
    city character varying(100) NOT NULL,
    district character varying(100) NOT NULL,
    state character varying(100) NOT NULL
);
COMMENT ON TABLE pincode_area IS 'City, district and state depend on pincode (3NF). Shared by locations and courts.';

CREATE TABLE location (
    location_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    landmark character varying(200),
    streetno character varying(50),
    pincode character varying(10) REFERENCES pincode_area(pincode) ON UPDATE CASCADE ON DELETE SET NULL
);
COMMENT ON TABLE location IS 'Place connected to the dispute. This is not the court.';

CREATE TABLE court (
    court_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_name character varying(200) NOT NULL,
    court_type character varying(50) NOT NULL,
    pincode character varying(10) REFERENCES pincode_area(pincode) ON UPDATE CASCADE ON DELETE SET NULL
);
COMMENT ON TABLE court IS 'Forum currently hearing a matter. Not a complete directory of Indian courts.';

CREATE TABLE lawyer (
    lawyer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fname character varying(50) NOT NULL,
    lname character varying(50) NOT NULL,
    designation character varying(50),
    phoneno character varying(15),
    bar_id character varying(50) UNIQUE,
    group_id integer REFERENCES practice_group(group_id) ON UPDATE CASCADE ON DELETE SET NULL
);
COMMENT ON TABLE lawyer IS 'Counsel engaged by this firm. bar_id is the bar enrolment number.';

CREATE TABLE client (
    client_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fname character varying(50) NOT NULL,
    lname character varying(50) NOT NULL,
    email character varying(100),
    address text,
    sex character(1),
    notes text,
    CONSTRAINT client_sex_check CHECK (sex IN ('M', 'F', 'O'))
);
COMMENT ON TABLE client IS 'Party the firm represents. Role is firm-centric and does not switch per case.';

CREATE TABLE opposing_party (
    party_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fname character varying(50) NOT NULL,
    lname character varying(50) NOT NULL,
    email character varying(100),
    address text,
    sex character(1),
    repeat_party boolean DEFAULT false,
    CONSTRAINT opposing_party_sex_check CHECK (sex IN ('M', 'F', 'O'))
);
COMMENT ON TABLE opposing_party IS 'Adverse party. repeat_party is set by trigger when the party appears on more than one matter.';

