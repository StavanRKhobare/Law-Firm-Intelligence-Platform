CREATE TRIGGER mark_repeat_party
    AFTER INSERT ON case_opposing_party
    FOR EACH ROW EXECUTE FUNCTION mark_repeat_opposing_party();

CREATE TRIGGER validate_case_dates
    BEFORE INSERT OR UPDATE ON legal_case
    FOR EACH ROW EXECUTE FUNCTION validate_legal_case_dates();

CREATE TRIGGER validate_evidence_filed_date
    BEFORE INSERT OR UPDATE ON evidence
    FOR EACH ROW EXECUTE FUNCTION validate_evidence_date();

