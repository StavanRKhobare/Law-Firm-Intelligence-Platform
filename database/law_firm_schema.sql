CREATE TABLE legal_case (
    case_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matter_title character varying(200) NOT NULL,
    matter_description text,
    case_number character varying(50) NOT NULL UNIQUE,
    date_cause date NOT NULL,
    date_filed date NOT NULL,
    status character varying(50) DEFAULT 'Filed',
    court_id integer REFERENCES court(court_id) ON UPDATE CASCADE ON DELETE SET NULL,
    location_id integer REFERENCES location(location_id) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT legal_case_date_check CHECK (date_filed >= date_cause),
    CONSTRAINT legal_case_status_check CHECK (status IN ('Filed', 'Hearing', 'Pending', 'Disposed'))
);
COMMENT ON TABLE legal_case IS 'Central matter. court_id is the current forum only. Assignment is in case_lawyer, not a lawyer foreign key here.';

CREATE INDEX idx_legal_case_status ON legal_case(status);
CREATE INDEX idx_legal_case_court ON legal_case(court_id);
CREATE INDEX idx_legal_case_date_filed ON legal_case(date_filed);
CREATE INDEX idx_legal_case_location ON legal_case(location_id);

CREATE TABLE case_lawyer (
    case_id integer NOT NULL REFERENCES legal_case(case_id) ON UPDATE CASCADE ON DELETE CASCADE,
    lawyer_id integer NOT NULL REFERENCES lawyer(lawyer_id) ON UPDATE CASCADE ON DELETE CASCADE,
    role character varying(50) NOT NULL,
    assigned_date date NOT NULL DEFAULT CURRENT_DATE,
    end_date date,
    PRIMARY KEY (case_id, lawyer_id),
    CONSTRAINT case_lawyer_role_check CHECK (role IN ('Lead Counsel', 'Associate', 'Research')),
    CONSTRAINT case_lawyer_date_check CHECK (end_date IS NULL OR end_date >= assigned_date)
);
COMMENT ON TABLE case_lawyer IS 'Many lawyers per matter. Composite primary key. One active lead is enforced by a partial unique index.';

CREATE UNIQUE INDEX one_active_lead_per_case
    ON case_lawyer (case_id)
    WHERE role = 'Lead Counsel' AND end_date IS NULL;
CREATE INDEX idx_case_lawyer_lawyer ON case_lawyer(lawyer_id);

CREATE TABLE case_client (
    case_id integer NOT NULL REFERENCES legal_case(case_id) ON UPDATE CASCADE ON DELETE CASCADE,
    client_id integer NOT NULL REFERENCES client(client_id) ON UPDATE CASCADE ON DELETE CASCADE,
    PRIMARY KEY (case_id, client_id)
);

CREATE TABLE case_opposing_party (
    case_id integer NOT NULL REFERENCES legal_case(case_id) ON UPDATE CASCADE ON DELETE CASCADE,
    party_id integer NOT NULL REFERENCES opposing_party(party_id) ON UPDATE CASCADE ON DELETE CASCADE,
    PRIMARY KEY (case_id, party_id)
);

CREATE TABLE client_phone_no (
    client_id integer NOT NULL REFERENCES client(client_id) ON UPDATE CASCADE ON DELETE CASCADE,
    phoneno character varying(15) NOT NULL,
    PRIMARY KEY (client_id, phoneno)
);

CREATE TABLE opposing_party_phone_no (
    party_id integer NOT NULL REFERENCES opposing_party(party_id) ON UPDATE CASCADE ON DELETE CASCADE,
    phoneno character varying(15) NOT NULL,
    PRIMARY KEY (party_id, phoneno)
);

CREATE TABLE matter_type (
    case_id integer NOT NULL REFERENCES legal_case(case_id) ON UPDATE CASCADE ON DELETE CASCADE,
    matter_type character varying(100) NOT NULL,
    PRIMARY KEY (case_id, matter_type)
);
COMMENT ON TABLE matter_type IS 'Multi-valued matter classification. Composite primary key removes a repeating group from legal_case.';

CREATE TABLE statute_section (
    case_id integer NOT NULL REFERENCES legal_case(case_id) ON UPDATE CASCADE ON DELETE CASCADE,
    statute_section character varying(50) NOT NULL,
    PRIMARY KEY (case_id, statute_section)
);
COMMENT ON TABLE statute_section IS 'Multi-valued statutory provisions cited on the matter.';

CREATE TABLE evidence (
    evidence_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description text,
    filed_date date NOT NULL,
    mongo_id character varying(100),
    status character varying(50) DEFAULT 'Received',
    lawyer_id integer REFERENCES lawyer(lawyer_id) ON UPDATE CASCADE ON DELETE SET NULL,
    case_id integer REFERENCES legal_case(case_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT evidence_status_check CHECK (status IN ('Received', 'Under Review', 'Filed', 'Produced'))
);
COMMENT ON TABLE evidence IS 'Document metadata in PostgreSQL. mongo_id points at the file in MongoDB.';

CREATE INDEX idx_evidence_case ON evidence(case_id);
CREATE INDEX idx_evidence_mongo ON evidence(mongo_id);

CREATE TABLE case_status_audit (
    audit_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id integer NOT NULL REFERENCES legal_case(case_id) ON UPDATE CASCADE ON DELETE CASCADE,
    old_status character varying(50),
    new_status character varying(50),
    changed_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    changed_by character varying(100) DEFAULT CURRENT_USER
);
COMMENT ON TABLE case_status_audit IS 'Trigger-maintained history of status changes. legal_case.status is only the current value.';

CREATE TABLE users (
    user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username character varying(50) NOT NULL UNIQUE,
    email character varying(100) NOT NULL UNIQUE,
    hashed_password character varying(255) NOT NULL,
    full_name character varying(100),
    role character varying(20),
    is_active boolean DEFAULT true,
    created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_role_check CHECK (role IN ('admin', 'lawyer', 'staff'))
);

