CREATE VIEW active_matters_view AS
SELECT
    lc.case_id,
    lc.case_number,
    lc.matter_title,
    lc.status,
    lc.date_cause,
    lc.date_filed,
    (SELECT concat(lw.fname, ' ', lw.lname)
     FROM case_lawyer cl
     JOIN lawyer lw ON cl.lawyer_id = lw.lawyer_id
     WHERE cl.case_id = lc.case_id AND cl.role = 'Lead Counsel' AND cl.end_date IS NULL
     LIMIT 1) AS lead_counsel,
    ct.court_name,
    ct.court_type,
    loc.landmark,
    pa.city,
    pa.district,
    (CURRENT_DATE - lc.date_filed) AS days_since_filing
FROM legal_case lc
LEFT JOIN court ct ON lc.court_id = ct.court_id
LEFT JOIN location loc ON lc.location_id = loc.location_id
LEFT JOIN pincode_area pa ON loc.pincode = pa.pincode
WHERE lc.status IN ('Filed', 'Hearing', 'Pending');

CREATE VIEW locality_caseload_view AS
SELECT
    loc.location_id,
    loc.landmark,
    loc.streetno,
    pa.city,
    pa.district,
    pa.state,
    pa.pincode,
    count(lc.case_id) AS total_matters,
    string_agg(DISTINCT mt.matter_type, ', ') AS matter_types,
    count(CASE WHEN lc.status = 'Filed' THEN 1 END) AS filed_matters,
    count(CASE WHEN lc.status = 'Disposed' THEN 1 END) AS disposed_matters,
    max(lc.date_filed) AS last_filing_date
FROM location loc
JOIN pincode_area pa ON loc.pincode = pa.pincode
LEFT JOIN legal_case lc ON loc.location_id = lc.location_id
LEFT JOIN matter_type mt ON lc.case_id = mt.case_id
GROUP BY loc.location_id, loc.landmark, loc.streetno, pa.city, pa.district, pa.state, pa.pincode
HAVING count(lc.case_id) > 0;

CREATE VIEW monthly_matter_stats AS
SELECT
    to_char(date_filed::timestamp, 'YYYY-MM') AS month,
    count(*) AS total_matters,
    count(DISTINCT location_id) AS unique_locations,
    count(DISTINCT court_id) AS courts_involved,
    sum(CASE WHEN status = 'Disposed' THEN 1 ELSE 0 END) AS disposed_matters,
    sum(CASE WHEN status = 'Filed' THEN 1 ELSE 0 END) AS filed_matters,
    sum(CASE WHEN status = 'Hearing' THEN 1 ELSE 0 END) AS hearing_matters,
    round(100.0 * sum(CASE WHEN status = 'Disposed' THEN 1 ELSE 0 END) / count(*), 2) AS disposal_rate_percent
FROM legal_case
GROUP BY to_char(date_filed::timestamp, 'YYYY-MM');

CREATE VIEW lawyer_performance_view AS
SELECT
    l.lawyer_id,
    concat(l.fname, ' ', l.lname) AS lawyer_name,
    l.designation,
    pg.group_name,
    count(DISTINCT lc.case_id) AS total_cases,
    sum(CASE WHEN lc.status IN ('Filed', 'Hearing', 'Pending') THEN 1 ELSE 0 END) AS active_cases,
    sum(CASE WHEN lc.status = 'Disposed' THEN 1 ELSE 0 END) AS disposed_cases,
    count(DISTINCT e.evidence_id) AS evidence_filed,
    round(
        100.0 * sum(CASE WHEN lc.status = 'Disposed' THEN 1 ELSE 0 END)
        / NULLIF(count(lc.case_id), 0),
        2
    ) AS disposal_rate
FROM lawyer l
LEFT JOIN practice_group pg ON l.group_id = pg.group_id
LEFT JOIN case_lawyer cl ON l.lawyer_id = cl.lawyer_id AND cl.end_date IS NULL
LEFT JOIN legal_case lc ON cl.case_id = lc.case_id
LEFT JOIN evidence e ON l.lawyer_id = e.lawyer_id
GROUP BY l.lawyer_id, l.fname, l.lname, l.designation, pg.group_name;

CREATE VIEW opposing_party_profile_view AS
SELECT
    op.party_id,
    concat(op.fname, ' ', op.lname) AS party_name,
    op.email,
    op.address,
    op.sex,
    op.repeat_party,
    count(DISTINCT cop.case_id) AS total_cases,
    string_agg(DISTINCT lc.case_number, ', ' ORDER BY lc.case_number) AS case_numbers,
    string_agg(DISTINCT mt.matter_type, ', ') AS matter_types,
    min(lc.date_cause) AS first_case_date,
    max(lc.date_cause) AS latest_case_date
FROM opposing_party op
LEFT JOIN case_opposing_party cop ON op.party_id = cop.party_id
LEFT JOIN legal_case lc ON cop.case_id = lc.case_id
LEFT JOIN matter_type mt ON lc.case_id = mt.case_id
GROUP BY op.party_id, op.fname, op.lname, op.email, op.address, op.sex, op.repeat_party;

