CREATE FUNCTION assign_lawyer_to_case(
    p_case_id integer,
    p_lawyer_id integer,
    p_role character varying,
    p_assigned_date date DEFAULT CURRENT_DATE
) RETURNS text
LANGUAGE plpgsql
AS $$
DECLARE
    v_name text;
    v_case_number character varying;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM lawyer WHERE lawyer_id = p_lawyer_id) THEN
        RAISE EXCEPTION 'Lawyer ID % does not exist', p_lawyer_id;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM legal_case WHERE case_id = p_case_id) THEN
        RAISE EXCEPTION 'Case ID % does not exist', p_case_id;
    END IF;
    IF p_role NOT IN ('Lead Counsel', 'Associate', 'Research') THEN
        RAISE EXCEPTION 'Role % is not allowed', p_role;
    END IF;

    IF p_role = 'Lead Counsel' THEN
        UPDATE case_lawyer
        SET end_date = p_assigned_date
        WHERE case_id = p_case_id
          AND role = 'Lead Counsel'
          AND end_date IS NULL
          AND lawyer_id <> p_lawyer_id;
    END IF;

    INSERT INTO case_lawyer (case_id, lawyer_id, role, assigned_date, end_date)
    VALUES (p_case_id, p_lawyer_id, p_role, p_assigned_date, NULL)
    ON CONFLICT (case_id, lawyer_id) DO UPDATE
        SET role = EXCLUDED.role,
            assigned_date = EXCLUDED.assigned_date,
            end_date = NULL;

    SELECT concat(fname, ' ', lname) INTO v_name FROM lawyer WHERE lawyer_id = p_lawyer_id;
    SELECT case_number INTO v_case_number FROM legal_case WHERE case_id = p_case_id;
    RETURN format('SUCCESS: %s assigned as %s on %s', v_name, p_role, v_case_number);
END;
$$;
COMMENT ON FUNCTION assign_lawyer_to_case IS 'Assigns counsel. Ends any other active lead before inserting a new Lead Counsel.';

CREATE FUNCTION dispose_case(p_case_id integer, p_lawyer_id integer DEFAULT NULL) RETURNS text
LANGUAGE plpgsql
AS $$
DECLARE
    v_case_number character varying;
    v_status character varying;
    v_evidence_count integer;
BEGIN
    SELECT case_number, status INTO v_case_number, v_status
    FROM legal_case WHERE case_id = p_case_id;

    IF v_case_number IS NULL THEN
        RAISE EXCEPTION 'Case ID % does not exist', p_case_id;
    END IF;
    IF v_status = 'Disposed' THEN
        RETURN format('Case %s is already disposed', v_case_number);
    END IF;

    SELECT count(*) INTO v_evidence_count FROM evidence WHERE case_id = p_case_id;
    IF v_evidence_count = 0 THEN
        RAISE NOTICE 'Warning: disposing case % without any evidence', v_case_number;
    END IF;

    UPDATE legal_case SET status = 'Disposed' WHERE case_id = p_case_id;
    RETURN format('SUCCESS: Case %s disposed (previous status: %s, evidence count: %s)',
                  v_case_number, v_status, v_evidence_count);
END;
$$;

CREATE FUNCTION practice_group_report(p_group_id integer)
RETURNS TABLE(
    lawyer_name text,
    designation character varying,
    phone_no character varying,
    total_cases bigint,
    active_cases bigint,
    disposed_cases bigint,
    evidence_filed bigint,
    disposal_rate numeric
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT
        concat(l.fname, ' ', l.lname),
        l.designation,
        l.phoneno,
        count(DISTINCT lc.case_id),
        count(DISTINCT CASE WHEN lc.status IN ('Filed', 'Hearing', 'Pending') THEN lc.case_id END),
        count(DISTINCT CASE WHEN lc.status = 'Disposed' THEN lc.case_id END),
        count(DISTINCT e.evidence_id),
        round(
            100.0 * count(DISTINCT CASE WHEN lc.status = 'Disposed' THEN lc.case_id END)
            / NULLIF(count(DISTINCT lc.case_id), 0),
            2
        )
    FROM lawyer l
    LEFT JOIN case_lawyer cl ON l.lawyer_id = cl.lawyer_id AND cl.end_date IS NULL
    LEFT JOIN legal_case lc ON cl.case_id = lc.case_id
    LEFT JOIN evidence e ON l.lawyer_id = e.lawyer_id
    WHERE l.group_id = p_group_id
    GROUP BY l.lawyer_id, l.fname, l.lname, l.designation, l.phoneno
    ORDER BY count(DISTINCT lc.case_id) DESC;
END;
$$;

CREATE FUNCTION get_complete_case_details(p_case_id integer)
RETURNS TABLE(
    case_number character varying,
    matter_title character varying,
    matter_description text,
    case_status character varying,
    cause_date date,
    filed_date date,
    lead_counsel text,
    practice_group text,
    court_name text,
    location_info text,
    clients text,
    opposing_parties text,
    matter_types text,
    statute_sections text,
    evidence_count bigint
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT
        lc.case_number,
        lc.matter_title,
        lc.matter_description,
        lc.status,
        lc.date_cause,
        lc.date_filed,
        (SELECT string_agg(concat(lw.fname, ' ', lw.lname), ', ')
         FROM case_lawyer cl
         JOIN lawyer lw ON cl.lawyer_id = lw.lawyer_id
         WHERE cl.case_id = lc.case_id AND cl.role = 'Lead Counsel' AND cl.end_date IS NULL),
        (SELECT string_agg(DISTINCT pg.group_name, ', ')
         FROM case_lawyer cl
         JOIN lawyer lw ON cl.lawyer_id = lw.lawyer_id
         JOIN practice_group pg ON lw.group_id = pg.group_id
         WHERE cl.case_id = lc.case_id AND cl.end_date IS NULL),
        ct.court_name,
        concat(loc.landmark, ', ', pa.city),
        (SELECT string_agg(concat(c.fname, ' ', c.lname), ', ')
         FROM case_client cc
         JOIN client c ON cc.client_id = c.client_id
         WHERE cc.case_id = lc.case_id),
        (SELECT string_agg(concat(op.fname, ' ', op.lname), ', ')
         FROM case_opposing_party cop
         JOIN opposing_party op ON cop.party_id = op.party_id
         WHERE cop.case_id = lc.case_id),
        (SELECT string_agg(mt.matter_type, ', ')
         FROM matter_type mt WHERE mt.case_id = lc.case_id),
        (SELECT string_agg(ss.statute_section, ', ')
         FROM statute_section ss WHERE ss.case_id = lc.case_id),
        (SELECT count(*) FROM evidence e WHERE e.case_id = lc.case_id)
    FROM legal_case lc
    LEFT JOIN court ct ON lc.court_id = ct.court_id
    LEFT JOIN location loc ON lc.location_id = loc.location_id
    LEFT JOIN pincode_area pa ON loc.pincode = pa.pincode
    WHERE lc.case_id = p_case_id;
END;
$$;

CREATE FUNCTION get_opposing_party_history(p_party_id integer)
RETURNS TABLE(
    case_id integer,
    case_number character varying,
    matter_title character varying,
    cause_date date,
    case_status character varying,
    matter_types text,
    lead_counsel text
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT
        lc.case_id,
        lc.case_number,
        lc.matter_title,
        lc.date_cause,
        lc.status,
        (SELECT string_agg(mt.matter_type, ', ') FROM matter_type mt WHERE mt.case_id = lc.case_id),
        (SELECT concat(lw.fname, ' ', lw.lname)
         FROM case_lawyer cl
         JOIN lawyer lw ON cl.lawyer_id = lw.lawyer_id
         WHERE cl.case_id = lc.case_id AND cl.role = 'Lead Counsel' AND cl.end_date IS NULL
         LIMIT 1)
    FROM legal_case lc
    JOIN case_opposing_party cop ON lc.case_id = cop.case_id
    WHERE cop.party_id = p_party_id
    ORDER BY lc.date_cause DESC;
END;
$$;

CREATE FUNCTION search_cases(
    p_start_date date DEFAULT NULL,
    p_end_date date DEFAULT NULL,
    p_city character varying DEFAULT NULL,
    p_status character varying DEFAULT NULL
)
RETURNS TABLE(
    case_id integer,
    case_number character varying,
    matter_title character varying,
    cause_date date,
    case_status character varying,
    location text,
    lead_counsel text
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT
        lc.case_id,
        lc.case_number,
        lc.matter_title,
        lc.date_cause,
        lc.status,
        concat(loc.landmark, ', ', pa.city),
        (SELECT concat(lw.fname, ' ', lw.lname)
         FROM case_lawyer cl
         JOIN lawyer lw ON cl.lawyer_id = lw.lawyer_id
         WHERE cl.case_id = lc.case_id AND cl.role = 'Lead Counsel' AND cl.end_date IS NULL
         LIMIT 1)
    FROM legal_case lc
    LEFT JOIN location loc ON lc.location_id = loc.location_id
    LEFT JOIN pincode_area pa ON loc.pincode = pa.pincode
    WHERE (p_start_date IS NULL OR lc.date_cause >= p_start_date)
      AND (p_end_date IS NULL OR lc.date_cause <= p_end_date)
      AND (p_city IS NULL OR pa.city ILIKE '%' || p_city || '%')
      AND (p_status IS NULL OR lc.status = p_status)
    ORDER BY lc.date_cause DESC;
END;
$$;

CREATE FUNCTION log_case_status_change() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.status IS DISTINCT FROM NEW.status THEN
        INSERT INTO case_status_audit (case_id, old_status, new_status)
        VALUES (NEW.case_id, OLD.status, NEW.status);
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION advance_case_on_evidence() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE legal_case
    SET status = 'Hearing'
    WHERE case_id = NEW.case_id
      AND status = 'Filed';
    RETURN NEW;
END;
$$;
COMMENT ON FUNCTION advance_case_on_evidence IS 'Filing the first evidence item moves a Filed matter to Hearing.';

CREATE FUNCTION mark_repeat_opposing_party() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF (SELECT count(*) FROM case_opposing_party WHERE party_id = NEW.party_id) > 1 THEN
        UPDATE opposing_party
        SET repeat_party = true
        WHERE party_id = NEW.party_id;
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION validate_legal_case_dates() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.date_filed < NEW.date_cause THEN
        RAISE EXCEPTION 'Filing date (%) cannot be before the cause of action (%)', NEW.date_filed, NEW.date_cause;
    END IF;
    IF NEW.date_cause > CURRENT_DATE THEN
        RAISE EXCEPTION 'Cause of action (%) cannot be in the future', NEW.date_cause;
    END IF;
    IF NEW.date_filed > CURRENT_DATE THEN
        RAISE EXCEPTION 'Filing date (%) cannot be in the future', NEW.date_filed;
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION validate_evidence_date() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_cause date;
BEGIN
    SELECT date_cause INTO v_cause FROM legal_case WHERE case_id = NEW.case_id;
    IF v_cause IS NOT NULL AND NEW.filed_date < v_cause THEN
        RAISE EXCEPTION 'Evidence date (%) cannot be before the cause of action (%)', NEW.filed_date, v_cause;
    END IF;
    IF NEW.filed_date > CURRENT_DATE THEN
        RAISE EXCEPTION 'Evidence date (%) cannot be in the future', NEW.filed_date;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER case_status_audit
    AFTER UPDATE ON legal_case
    FOR EACH ROW EXECUTE FUNCTION log_case_status_change();

CREATE TRIGGER evidence_advances_status
    AFTER INSERT ON evidence
    FOR EACH ROW EXECUTE FUNCTION advance_case_on_evidence();

CREATE TRIGGER mark_repeat_party
    AFTER INSERT ON case_opposing_party
    FOR EACH ROW EXECUTE FUNCTION mark_repeat_opposing_party();

CREATE TRIGGER validate_case_dates
    BEFORE INSERT OR UPDATE ON legal_case
    FOR EACH ROW EXECUTE FUNCTION validate_legal_case_dates();

CREATE TRIGGER validate_evidence_filed_date
    BEFORE INSERT OR UPDATE ON evidence
    FOR EACH ROW EXECUTE FUNCTION validate_evidence_date();

